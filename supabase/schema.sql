-- =============================================================
-- 智能任务管理系统 · Supabase 数据库初始化脚本
-- 使用方法：Supabase 控制台 → 左侧 SQL Editor → New query → 粘贴全部 → Run
-- =============================================================

-- 1) 创建 tasks 表
create table if not exists tasks (
  id          bigint generated by default as identity primary key,
  title       text        not null,
  priority    text        not null default '中' check (priority in ('高', '中', '低')),
  completed   boolean     not null default false,
  created_at  timestamptz not null default now(),
  due_date    date
);

-- 如果你的表是之前就建好的（缺少截止日期字段），执行下面这句补齐
alter table tasks add column if not exists due_date date;

-- 2) 按创建时间倒序查询会更快
create index if not exists tasks_created_at_idx on tasks (created_at desc);

-- 3) 开启行级安全（RLS）并允许匿名读写
--    注意：这是教学演示用的宽松策略，正式项目请改成「登录用户只能操作自己的数据」
alter table tasks enable row level security;

drop policy if exists "Allow anon read"   on tasks;
drop policy if exists "Allow anon insert" on tasks;
drop policy if exists "Allow anon update" on tasks;
drop policy if exists "Allow anon delete" on tasks;

create policy "Allow anon read"   on tasks for select using (true);
create policy "Allow anon insert" on tasks for insert with check (true);
create policy "Allow anon update" on tasks for update using (true) with check (true);
create policy "Allow anon delete" on tasks for delete using (true);

-- 4) 可选：插入几条示例数据
insert into tasks (title, priority, completed, due_date) values
  ('完成实训报告初稿', '高', false, current_date + 1),
  ('复习 React 组件状态管理', '中', false, current_date - 1),
  ('注册 Supabase 并创建 tasks 表', '高', true, null),
  ('整理这周的学习笔记', '低', false, current_date + 3)
on conflict do nothing;
